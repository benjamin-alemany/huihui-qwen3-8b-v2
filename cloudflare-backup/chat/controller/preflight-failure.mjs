import {SessionError} from './session-policy.mjs';
import {safeTailFailure} from './tails.mjs';

// These are reviewed classifications, never arbitrary upstream message text.
const SESSION_CODES=new Set([
 'ACCOUNT_HAS_PODS','APPROVAL_ALREADY_USED','APPROVAL_LIMIT','BUDGET_EXHAUSTED',
 'CATALOG_INVALID','GUARD_ARM_FAILED','GUARD_DISARM_PENDING','GUARD_RECEIPTS_EXPIRED','GUARD_VERSION_CHANGED','HOURLY_LIMIT','INVALID_DURATION',
 'KEY_GENERATION_FAILED','LAUNCH_LOCKED','NO_STOCK','PRICE_CHANGED','QUOTE_CHANGED',
 'RESIDUAL_RESOURCE_REVIEW_REQUIRED','SESSION_CHANGED','SESSION_LEASE_CHANGED',
 'HYPERSTACK_TARGET_UNVERIFIED','HYPERSTACK_RELEASE_UNPINNED',
 'HYPERSTACK_RESERVATION_INVALID','HYPERSTACK_CATALOG_INVALID','HYPERSTACK_QUOTE_INVALID',
 'HYPERSTACK_CREATE_BINDING_INVALID','HYPERSTACK_RESIDUAL_RESOURCE_REVIEW_REQUIRED'
]);
const HYPERSTACK_CODES=new Set([
 'HYPERSTACK_NOT_CONFIGURED','HYPERSTACK_REQUEST_UNCONFIRMED','HYPERSTACK_RESPONSE_INVALID',
 'HYPERSTACK_INVENTORY_INVALID','HYPERSTACK_INVENTORY_LIMIT','HYPERSTACK_INVENTORY_INCOMPLETE',
 'HYPERSTACK_INVENTORY_OPTIONS_INVALID','HYPERSTACK_CATALOG_INVALID',
 'HYPERSTACK_FLAVOR_UNVERIFIED','HYPERSTACK_FLAVOR_UNAVAILABLE','HYPERSTACK_IMAGE_UNVERIFIED','HYPERSTACK_IMAGE_INCOMPATIBLE',
 'HYPERSTACK_COMPATIBILITY_UNVERIFIED','HYPERSTACK_ENVIRONMENT_UNVERIFIED',
 'HYPERSTACK_KEYPAIR_UNVERIFIED','HYPERSTACK_STOCK_INVALID','HYPERSTACK_PRICE_UNVERIFIED',
 'HYPERSTACK_PRICE_INVALID','HYPERSTACK_PRICE_NOT_ACTIVE','HYPERSTACK_PRICE_EXPIRING',
 'HYPERSTACK_EXTRA_COMPUTE_PRICE','HYPERSTACK_RATE_TOO_HIGH','HYPERSTACK_TIMESTAMP_INVALID',
 'HYPERSTACK_ID_INVALID','HYPERSTACK_VM_INVALID','HYPERSTACK_IP_INVALID',
 'HYPERSTACK_TARGET_INVALID','HYPERSTACK_RATE_LIMIT_INVALID'
]);
export function safePreflightFailure(error){
 if(error instanceof SessionError&&SESSION_CODES.has(error.code))return error.code;
 const tail=safeTailFailure(error);
 if(tail!=='GUARD_HEARTBEAT_NOT_VERIFIED'||error?.code==='GUARD_HEARTBEAT_NOT_VERIFIED')return tail;
 if(HYPERSTACK_CODES.has(error?.code))return error.code;
 if(HYPERSTACK_CODES.has(error?.message))return error.message;
 return 'PREFLIGHT_FAILED';
}
