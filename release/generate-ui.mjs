// Deterministic credential-free browser settings from the canonical release.
import {readFile,writeFile} from 'node:fs/promises';
import release from './manifest.json' with {type:'json'};
const path=new URL('../cloudflare-backup/chat/site/release-ui.js',import.meta.url);
const settings=release.sessions;
if(!Array.isArray(settings.allowedMinutes)||settings.allowedMinutes.join()!=='15,30,60'||!settings.allowedMinutes.includes(settings.defaultMinutes))throw Error('Unsupported release session policy');
const text='// Generated by release/generate-ui.mjs; edit release/manifest.json.\n'+
 'export const SESSION_MINUTES=Object.freeze('+JSON.stringify(settings.allowedMinutes)+');\n'+
 'export const DEFAULT_MINUTES='+JSON.stringify(settings.defaultMinutes)+';\n';
if(process.argv.length!==3||!['--write','--check'].includes(process.argv[2]))throw Error('Use --write or --check');
if(process.argv[2]==='--write')await writeFile(path,text);
else if(await readFile(path,'utf8')!==text)throw Error('Browser session policy differs from canonical release');
const cache=JSON.parse(await readFile(new URL('../chat/model-manifest.json',import.meta.url),'utf8'));
if(cache.model!==release.model.repository||cache.revision!==release.model.revision)throw Error('Offline checkpoint differs from release');
const docker=await readFile(new URL('../vm/Dockerfile.inference',import.meta.url),'utf8');
if(docker.match(/^FROM (.+)$/m)?.[1]!==release.artifact.reusableOfflineBase)throw Error('VM overlay base differs from release');
console.log('Release/browser/checkpoint/base consistency verified; no runtime acceptance implied.');
